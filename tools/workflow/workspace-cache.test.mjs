import assert from 'node:assert/strict';
import childProcess, { execFileSync, spawnSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, realpathSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { syncBuiltinESMExports } from 'node:module';
import { tmpdir } from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { withRepository } from './runtime.mjs';
import { pythonCacheRetirementFiles, verifiedPythonCache } from './workspace-cache.mjs';

const packagePath = 'apps/cpu-production/tools/xchange-print-agent';
const cachePath = `${packagePath}/__pycache__`;
const moduleNames = ['agent', 'test_agent'];
const hasPython314 = spawnSync('python', ['-I', '-B', '-c',
  "import sys; sys.exit(not (sys.implementation.name == 'cpython' and sys.version_info[:2] == (3, 14)))",
], { windowsHide: true, timeout: 15000 }).status === 0;

function fixture(t, { linked = false } = {}) {
  const temporary = realpathSync(mkdtempSync(path.join(tmpdir(), 'fika-python-cache-')));
  t.after(() => rmSync(temporary, { recursive: true, force: true }));
  const canonical = path.join(temporary, 'canonical');
  const directory = linked ? path.join(temporary, 'task') : canonical;
  const cacheDirectory = path.join(directory, cachePath);
  const sources = moduleNames.map(name => path.join(directory, packagePath, `${name}.py`));
  const caches = moduleNames.map(name => path.join(cacheDirectory, `${name}.cpython-314.pyc`));
  mkdirSync(path.join(canonical, packagePath), { recursive: true });
  for (const [index, name] of moduleNames.entries()) {
    // Compiling is sufficient. Executing either source would fail the positive case.
    writeFileSync(path.join(canonical, packagePath, `${name}.py`), `raise RuntimeError("module ${index} was executed")\n`);
  }
  const git = (...args) => execFileSync('git', [
    '-c', 'user.name=Fixture', '-c', 'user.email=fixture@example.invalid', '-c', 'commit.gpgSign=false',
    '-c', 'core.hooksPath=.git/unused-hooks', '-c', 'core.autocrlf=false', ...args,
  ], { cwd: canonical, encoding: 'utf8', windowsHide: true }).trim();
  git('init', '--quiet');
  git('add', '--', ...moduleNames.map(name => `${packagePath}/${name}.py`));
  git('commit', '--quiet', '-m', 'Fixture source');
  const head = git('rev-parse', 'HEAD');
  if (linked) git('worktree', 'add', '--quiet', '--detach', directory, head);
  mkdirSync(cacheDirectory, { recursive: true });
  const verify = (relative = cachePath) =>
    withRepository(canonical, () => verifiedPythonCache({ directory }, relative, head));
  const compile = () => execFileSync('python', ['-I', '-B', '-c', [
    'import py_compile, sys',
    'for filename in sys.argv[1:]:',
    '    py_compile.compile(filename, doraise=True, optimize=0, invalidation_mode=py_compile.PycInvalidationMode.TIMESTAMP)',
  ].join('\n'), ...sources], { cwd: directory, windowsHide: true, timeout: 15000 });
  return { cacheDirectory, sources, caches, verify, compile };
}

test('retirement enumerates only the two print-agent cache paths', () => {
  assert.deepEqual(pythonCacheRetirementFiles(cachePath), [
    `${cachePath}/agent.cpython-314.pyc`, `${cachePath}/test_agent.cpython-314.pyc`,
  ]);
  for (const relative of ['__pycache__', `${cachePath}/agent.cpython-314.pyc`, `${cachePath}/../__pycache__`]) {
    assert.deepEqual(pythonCacheRetirementFiles(relative), []);
  }
});

test('verifies timestamp bytecode against the tracked source at the supplied head', {
  skip: !hasPython314 && 'requires CPython 3.14',
}, async t => {
  const { cacheDirectory, sources, caches, verify, compile } = fixture(t);
  compile();
  await t.test('both genuine CPython cache files match', () => assert.equal(verify(), true));
  await t.test('a different spelling of the same directory is rejected', () => {
    assert.equal(verify(`${cachePath}/../__pycache__`), false);
  });
  await t.test('an additional file protects the entire directory', t => {
    const extra = path.join(cacheDirectory, 'other.cpython-314.pyc');
    writeFileSync(extra, readFileSync(caches[0]));
    t.after(() => rmSync(extra));
    assert.equal(verify(), false);
  });
  await t.test('an altered second cache file is rejected', t => {
    const original = readFileSync(caches[1]);
    const corrupted = Buffer.from(original);
    corrupted[corrupted.length - 1] ^= 1;
    writeFileSync(caches[1], corrupted);
    t.after(() => writeFileSync(caches[1], original));
    assert.equal(verify(), false);
  });
  await t.test('locally changed source is rejected even with matching regenerated bytecode', () => {
    writeFileSync(sources[0], 'raise RuntimeError("altered source")\n');
    compile();
    assert.equal(verify(), false);
  });
});

test('retirement verifies orphaned task bytecode against canonical source', {
  skip: !hasPython314 && 'requires CPython 3.14',
}, t => {
  const { sources, caches, verify, compile } = fixture(t, { linked: true });
  compile();
  for (const source of sources) rmSync(source);
  assert.equal(verify(), true);
  const altered = readFileSync(caches[1]);
  altered[altered.length - 1] ^= 1;
  writeFileSync(caches[1], altered);
  assert.equal(verify(), false);
});

test('an unavailable Python runtime protects the cache', t => {
  const { caches, sources, verify } = fixture(t);
  for (const [index, cache] of caches.entries()) {
    // A timestamp header reaches the compiler check even on hosts without CPython 3.14.
    const source = statSync(sources[index]);
    const header = Buffer.alloc(16);
    Buffer.from('2b0e0d0a', 'hex').copy(header);
    header.writeUInt32LE(Math.floor(source.mtimeMs / 1000), 8);
    header.writeUInt32LE(source.size, 12);
    writeFileSync(cache, header);
  }
  let attempted = false;
  const originalSpawn = childProcess.spawnSync;
  const mock = t.mock.method(childProcess, 'spawnSync', (program, ...args) => {
    if (program !== 'python') return originalSpawn(program, ...args);
    attempted = true;
    return { status: null, error: Object.assign(new Error('missing executable'), { code: 'ENOENT' }) };
  });
  syncBuiltinESMExports();
  t.after(() => {
    mock.mock.restore();
    syncBuiltinESMExports();
  });
  assert.equal(verify(), false);
  assert.equal(attempted, true);
});
