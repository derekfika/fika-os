// @ts-nocheck -- Runtime cross-app harness; each application is typechecked independently.
import assert from "node:assert/strict";
import test from "node:test";
import { mkdtemp, mkdir, writeFile, readFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { randomUUID } from "node:crypto";

// Explicitly opt in: every write is confined to a demo emulator and private local stores.
test("emulator: weekly publication, one-off amendment and signed allergen handoff converge end to end", { skip: process.env.FIKA_RECOVERY_EMULATOR_TEST !== "1", timeout: 120_000 }, async () => {
  assert.equal(process.env.FIREBASE_PROJECT_ID, "demo-fika-os");
  assert.match(process.env.FIRESTORE_EMULATOR_HOST || "", /^(127\.0\.0\.1|localhost):\d+$/);
  assert.equal(process.env.FIKA_RUNTIME_MODE, "local");
  const originalCwd = process.cwd();
  const isolated = await mkdtemp(join(tmpdir(), "fika-recovery-sprint-"));
  process.env.MENU_PLANNING_DB_PATH = join(isolated, "operational.sqlite");
  process.env.MENU_PLANNING_TEST_MODE = "1";
  process.env.FIKA_CPU_PLAN_STORE = "memory";
  process.env.FIKA_SNAPSHOT_DIR = join(isolated, "packets");
  process.chdir(isolated);
  try {
    const importApp = (relative: string) => import(new URL(`${relative}.ts`, import.meta.url).href);
    const menu = await import("../lib/rolling-menu");
    const publications = await import("../lib/menu-publication");
    const { applyRollingEntryPatch } = await import("../lib/rolling-command");
    const hub = await importApp("../../integration-hub/lib/production-domain");
    const { db } = await importApp("../../integration-hub/lib/firebase-admin");
    const { stableDocumentId } = await importApp("../../integration-hub/lib/canonical-editor");
    const { GOVERNED_OPLOCS } = await importApp("../../../packages/server-shared/src/governed-oplocs");
    const { parseExternalProductionMaterialisation, approvedAllergenSnapshotSchema } = await importApp("../../../packages/server-shared/src/external-production");
    const cpuDecoder = await importApp("../../cpu-production/lib/menu-planning-week-packet");
    const diDecoder = await importApp("../../delivered-in/lib/menu-planning-week-packet");
    const { projectPublishedWeeks, assertAuthorisedOploc } = await importApp("../../delivered-in/lib/projection");
    const { stampAllergenReviews } = await importApp("../../cpu-production/app/lib/allergen-review-stamp");
    const { buildCpuPacketItems } = await importApp("../../cpu-production/lib/cpu-packet-identity");
    const bundles = await importApp("../../../packages/server-shared/src/daily-signed-oploc-bundle");
    const { readCpuDailySignedPacket, cpuDailyPacketReview } = await importApp("../../delivered-in/lib/cpu-daily-signed-packet");
    const { buildDeliveredInDayProjection } = await importApp("../../delivered-in/lib/delivered-in-projection-materialiser");
    const { fulfilmentFromProductionOrder } = await importApp("../../shared/fulfilment-requirement");
    const { logisticsJobForRequirement } = await importApp("../../logistics/lib/logistics-materialisation");
    const { createLoad, compatibleLoad } = await importApp("../../logistics/lib/delivery-loads");
    const { combineStop } = await importApp("../../logistics/lib/planning");
    const snapshot = menu.emptyWeek("2098-11-03", "isolated-planner");
    const originalWeekId = snapshot.week.id;
    snapshot.week.id += `:recovery:${randomUUID()}`;
    snapshot.days.forEach(day => { day.id = day.id.replace(originalWeekId, snapshot.week.id); });
    snapshot.week.dayIds = snapshot.days.map(day => day.id);
    const governed = [GOVERNED_OPLOCS[0], GOVERNED_OPLOCS[2]];
    const ids = new Set(governed.map(site => site.id));
    snapshot.entries = snapshot.days.slice(0, 5).flatMap((day, dayIndex) => {
      const oneOff = { id: `${day.id}:one-off:fixture`, label: `Synthetic event ${dayIndex}`, address: `${dayIndex + 10} Test Street`, addressStatus: "confirmed" as const, contact: "Synthetic receiving team", deliveryInstructions: "Use reception" };
      day.oneOffDestinations = [oneOff];
      return ["SOUP", "SALAD 1"].map((slot, index) => {
        const row = { id: `${day.id}:entry:${index}`, dayId: day.id, date: day.date, slot, itemId: `dish:fixture:${index}`, itemLabel: `Synthetic dish ${index}`, portions: 16, allocations: [...governed.map((site, i) => ({ destinationId: site.id, destinationLabel: site.label, quantity: i + 4 })), { oneOffDestinationId: oneOff.id, destinationLabel: oneOff.label, destinationAddress: oneOff.address, quantity: 7 }], allergens: {}, audit: [] };
        applyRollingEntryPatch(row, { explicitAllergenDeclaration: true, confirmAllergenReview: true, allergens: index ? { no_key_allergens: "contains" } : { tree_nuts: "contains", gluten: "contains", sesame: "may_contain" }, allergenDetailNotes: index ? "" : "Almond and wheat", mayContainNotes: index ? "" : "Shared sesame equipment" }, { actor: "isolated-planner", at: "2098-11-03T08:00:00Z" });
        return row;
      });
    });
    snapshot.week.entryIds = snapshot.entries.map(row => row.id);
    snapshot.days.forEach(day => { day.entryIds = snapshot.entries.filter(row => row.dayId === day.id).map(row => row.id); });
    const catalogue = join(isolated, "local-data/menu-planning/canonical-menu-items.json");
    await mkdir(dirname(catalogue), { recursive: true });
    await writeFile(catalogue, JSON.stringify({ items: [0, 1].map(index => ({ canonicalId: `dish:fixture:${index}`, displayName: `Synthetic dish ${index}`, reviewStatus: "approved" })) }));
    await menu.saveSnapshot(snapshot);
    const { MenuPlanningFirestoreRepository } = await import("../lib/firestore-operational-store");
    const menuRepository = new MenuPlanningFirestoreRepository();
    await menuRepository.createRollingSnapshot(snapshot);
    const storedWeek = await menuRepository.getWeekSnapshot(snapshot.week.id);
    assert.deepEqual(storedWeek!.entries[0].allocations[2], snapshot.entries[0].allocations[2]);
    assert.equal(Object.hasOwn(storedWeek!.entries[0].allocations[2], "destinationId"), false);
    assert.deepEqual(storedWeek!.entries[1].noKeyDeclaration, snapshot.entries[1].noKeyDeclaration);
    await menuRepository.db.terminate();
    const publication = await publications.createPublishedMenuWeek(snapshot.week.id, {}, "isolated-planner", ids);
    assert.equal(publication.days.filter(day => day.status === "published").length, 5);
    assert.equal(cpuDecoder.decodeMenuPlanningWeekPacket(publication.weekPacket).days.length, 5);
    const decoded = diDecoder.decodeMenuPlanningWeekPacket(publication.weekPacket);
    const source = diDecoder.packetPublication(decoded);
    const allEvents = await publications.listMenuPublicationEvents();
    const events = allEvents.filter(event => event.eventType === "production.materialise");
    assert.equal(events.length, 15);
    const actor = { uid: "isolated-materialiser", name: "Isolated Materialiser", role: "integration-admin" as const, synthetic: true as const };
    const materialised = [];
    for (const event of events) {
      const payload = parseExternalProductionMaterialisation(event.payload);
      const first = await hub.materialiseExternalProductionOrder(actor, payload);
      const replay = await hub.materialiseExternalProductionOrder(actor, payload);
      assert.equal(replay.duplicate, true);
      assert.equal(replay.order.version, first.order.version);
      assert.equal(first.order.lines.reduce((sum, line) => sum + line.customerQuantity, 0), payload.lines.reduce((sum, line) => sum + line.quantity, 0));
      const persisted = (await db.collection("fikaProductionOrdersV1").doc(stableDocumentId(first.order.canonicalId)).get()).data()!;
      assert.deepEqual(persisted.destination, payload.destination);
      assert.deepEqual(persisted.lines[0].approvedAllergenSnapshot.allergens, payload.lines[0].approvedAllergenSnapshot!.allergens);
      materialised.push({ order: first.order, payload });
    }
    const oneOff = materialised.find(value => value.payload.destination?.kind === "one-off")!;
    assert.equal(oneOff.order.destination?.kind, "one-off");
    assert.equal((await db.collection("fikaProductionOrdersV1").where("sourceEntityId", "==", oneOff.payload.sourceEntityId).get()).size, 3);
    const requirements = await db.collection("fikaFulfilmentRequirementsV1").where("sourceEntityId", "==", oneOff.order.canonicalId).get();
    assert.equal(requirements.size, 1);
    const requirement = requirements.docs[0].data() as ReturnType<typeof fulfilmentFromProductionOrder>;
    assert.deepEqual(requirement.destination, oneOff.payload.destination);
    assert.equal(requirement.readyAt, undefined, "missing routing time does not invent midnight");
    const job = logisticsJobForRequirement(requirement, undefined, "isolated-dispatcher", "2098-11-03T09:00:00Z");
    const load = createLoad({ serviceDate: job.serviceDate, originOplocId: job.originOplocId!, destinationOplocId: job.destinationOplocId!, destination: job.destination, scheduledTime: "11:30", by: "isolated-dispatcher" });
    assert.ok(compatibleLoad(job, load));
    const stop = combineStop([], { runId: "synthetic-run", locationOplocId: job.destinationOplocId!, locationLabel: job.destinationLabelSnapshot!, requirement, by: "isolated-dispatcher" });
    assert.equal(stop.locationOplocId, "");
    assert.equal(stop.oneOffEndpointId, oneOff.payload.destinationOplocId);
    assert.equal(stop.locationAddressSnapshot, oneOff.payload.destination?.kind === "one-off" ? oneOff.payload.destination.address : "");
    assert.throws(() => assertAuthorisedOploc({ email: "isolated-site", oplocIds: [governed[0].id], permissions: [] }, oneOff.payload.destinationOplocId), { status: 403 });
    assert.doesNotThrow(() => assertAuthorisedOploc({ email: "isolated-admin", oplocIds: [], permissions: [], canViewOneOffDestinations: true, oneOffDestinationIds: [oneOff.payload.destinationOplocId] }, oneOff.payload.destinationOplocId));
    const menuItems = oneOff.order.lines.map(line => ({ id: `item:${line.canonicalId}`, sourceLineId: line.canonicalId, name: line.itemName, note: "", subItems: [{ id: `sub:${line.canonicalId}`, name: line.itemName, quantity: line.customerQuantity, allergens: approvedAllergenSnapshotSchema.parse(line.approvedAllergenSnapshot).allergens, allergenDetailNotes: line.approvedAllergenSnapshot!.allergenDetailNotes, mayContainNotes: line.approvedAllergenSnapshot!.mayContainNotes, ...(line.approvedAllergenSnapshot?.noKeyDeclaration ? { noKeyDeclaration: { declared: true as const } } : {}), note: "", evidenceStatus: "completed" as const }] }));
    const reviewed = stampAllergenReviews([], menuItems, "isolated-cpu-chef", "2098-11-03T09:00:00Z");
    const signed = bundles.buildDailySignedOplocBundle({ bundleId: "isolated-bundle", serviceDate: oneOff.order.serviceDate!, oploc: { id: oneOff.payload.destinationOplocId, name: oneOff.payload.destinationLabel! }, source: { revision: 1, contentHash: oneOff.payload.sourceContentHash! }, signatures: ["production_chef", "head_chef_site_manager"].map(role => ({ role: role as "production_chef" | "head_chef_site_manager", printedName: "Isolated Chef", actor: "isolated-cpu-chef", signedAt: "2098-11-03T10:00:00Z" })), masterSheet: { contentHash: "a".repeat(64), fileId: "isolated-master" }, pdf: { contentHash: "b".repeat(64), fileId: "isolated-pdf", url: "https://example.invalid/isolated.pdf" }, items: buildCpuPacketItems(reviewed, oneOff.order) });
    const encoded = bundles.encodeDailySignedOplocBundlePackage({ ...signed.bundle, status: "published", publishedAt: "2098-11-03T10:00:00Z" }, signed.packet, 1);
    const packetRoot = process.env.FIKA_SNAPSHOT_DIR!;
    await mkdir(dirname(join(packetRoot, encoded.manifest.objectName)), { recursive: true });
    await writeFile(join(packetRoot, encoded.manifest.objectName), encoded.bytes);
    const manifestPath = join(packetRoot, "manifests", `${bundles.dailyBundleManifestKey(oneOff.order.serviceDate!, oneOff.payload.destinationOplocId).replaceAll("/", "_")}.json`);
    await mkdir(dirname(manifestPath), { recursive: true });
    await writeFile(manifestPath, JSON.stringify(encoded.manifest));
    assert.deepEqual(await readFile(join(packetRoot, encoded.manifest.objectName)), Buffer.from(encoded.bytes));
    const packet = await readCpuDailySignedPacket(oneOff.order.serviceDate!, oneOff.payload.destinationOplocId, oneOff.payload.sourceContentHash!);
    assert.ok(packet);
    const day = projectPublishedWeeks([source], oneOff.payload.destinationOplocId, ids, source.weekCommencing)[0].days.find(day => day.date === oneOff.order.serviceDate)!;
    const destination = oneOff.payload.destination!;
    const projection = await buildDeliveredInDayProjection({ request: {} as never, site: { oplocId: destination.id, label: destination.label, destination }, day, governed: false, loadReview: async () => cpuDailyPacketReview(packet) });
    assert.ok(projection.entries.every(row => row.allergensVisible));
    assert.equal(projection.entries[0].allergenDetailNotes, "Almond and wheat");
    assert.equal(projection.entries[0].mayContainNotes, "Shared sesame equipment");
    assert.equal(projection.entries[1].allergens.no_key_allergens, "contains");
    assert.equal(projection.oplocLabel, destination.label);
    const changed = await menu.getWeek(snapshot.week.id);
    changed.days[0].oneOffDestinations![0].address = "99 Amended Test Street";
    changed.entries.find(row => row.dayId === changed.days[0].id)!.allocations[2].quantity += 2;
    changed.week.version += 1;
    await menu.saveSnapshot(changed, changed.week.version - 1);
    const amendment = await publications.createPublishedMenuWeek(changed.week.id, {}, "isolated-planner", ids);
    const amendmentEvents = (await publications.listMenuPublicationEvents()).filter(event => event.eventType === "production.materialise" && !events.some(prior => prior.eventId === event.eventId));
    const amendedEvent = amendmentEvents.map(event => parseExternalProductionMaterialisation(event.payload)).find(payload => payload.destinationOplocId === destination.id)!;
    assert.ok(amendedEvent);
    const amendedOrder = (await hub.materialiseExternalProductionOrder(actor, amendedEvent)).order;
    assert.equal(amendedOrder.canonicalId, oneOff.order.canonicalId);
    assert.equal(amendedOrder.sourceVersion, 2);
    const amendedReq = (await db.collection("fikaFulfilmentRequirementsV1").where("sourceEntityId", "==", amendedOrder.canonicalId).get()).docs[0].data() as typeof requirement;
    assert.equal(amendedReq.destination?.kind === "one-off" ? amendedReq.destination.address : "", "99 Amended Test Street");
    assert.equal(compatibleLoad(logisticsJobForRequirement(amendedReq, job, "isolated-dispatcher", "2098-11-03T11:00:00Z"), load), false, "changed routing invalidates the old load snapshot");
    const amendedDay = diDecoder.packetPublication(diDecoder.decodeMenuPlanningWeekPacket(amendment.weekPacket)).days.find(day => day.sourceDayId === oneOff.payload.sourceEntityId)!;
    await assert.rejects(readCpuDailySignedPacket(amendedDay.date, destination.id, amendedDay.contentHash!), { code: "CPU_REVIEW_LINEAGE_MISMATCH" });
    const oldReplay = await hub.materialiseExternalProductionOrder(actor, oneOff.payload);
    assert.equal(oldReplay.duplicate, true);
    assert.equal(oldReplay.order.sourceVersion, 2);
    const withdrawn = await hub.materialiseExternalProductionOrder(actor, { ...amendedEvent, status: "withdrawn" });
    assert.equal(withdrawn.order.status, "cancelled");
    assert.equal((await db.collection("fikaFulfilmentRequirementsV1").where("sourceEntityId", "==", withdrawn.order.canonicalId).get()).docs[0].data().status, "withdrawn");
    assert.equal((await hub.materialiseExternalProductionOrder(actor, amendedEvent)).order.status, "cancelled", "replay cannot resurrect withdrawn work");
  } finally {
    process.chdir(originalCwd);
    // Retain isolated evidence for inspection; no production or shared test data was touched.
  }
});
