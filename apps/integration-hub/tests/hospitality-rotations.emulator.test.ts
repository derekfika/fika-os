import test from "node:test";
import assert from "node:assert/strict";
import { NextRequest } from "next/server";
import { getApps, initializeApp } from "firebase-admin/app";
import { getFirestore } from "firebase-admin/firestore";
import { stableDocumentId } from "@fika/server-shared/stable-document-id";
import { RotationStore, ROTATION_COLLECTION } from "../lib/hospitality-rotations/store";
import { rotationHandlers } from "../lib/hospitality-rotations/http";
import { rotationFixture } from "./hospitality-rotations.test";
import { authoriseRotation } from "../lib/hospitality-rotations/auth";
import { MemoryAuthModRepository } from "../lib/authmod-core/memory-repository";
import { V1_APPLICATIONS, type AuthPrincipal } from "../lib/authmod-core/model";
import { createAuthIdentity } from "../lib/authmod-core/identity";
import { grantStandardApplicationAccess } from "../lib/authmod-core/grants";
import { grantAuthority, revokeAuthority } from "../lib/authmod-core/authority";

const enabled = process.env.FIKA_ROTATIONS_EMULATOR_TEST === "true";
test("emulator: rotation API commits evidence atomically, rejects stale writers and replays without duplicate publication", { skip: !enabled }, async () => {
  assert.equal(process.env.FIREBASE_PROJECT_ID, "demo-fika-os");
  assert.match(process.env.FIRESTORE_EMULATOR_HOST || "", /^(127\.0\.0\.1|localhost):\d+$/);
  assert.equal(process.env.FIKA_RUNTIME_MODE, "local");
  const app = getApps().find(value => value.name === "rotation-test") || initializeApp({ projectId: "demo-fika-os" }, "rotation-test");
  const db = getFirestore(app);
  // A dedicated emulator process/project; never clear shared emulator or production state.
  const existing = await db.collection(ROTATION_COLLECTION).doc("company").get();
  assert.equal(existing.exists, false, "Run this suite on a fresh isolated emulator");
  const store = new RotationStore(db, () => new Date("2026-10-28T12:00:00Z"));
  const repository = new MemoryAuthModRepository({ applications: [...V1_APPLICATIONS] });
  const operator: AuthPrincipal = { type: "interactive", id: "operator", displayName: "Synthetic operator" };
  const identity = await createAuthIdentity(repository, { actor: operator, displayName: "Synthetic manager", email: "manager@example.test", provenance: "migration" });
  const principal: AuthPrincipal = { type: "interactive", id: identity.id, displayName: identity.displayName };
  await grantStandardApplicationAccess(repository, { identityId: identity.id, appId: "hospitality-booking", actor: operator });
  const grants = [];
  for (const action of ["View", "Manage", "Publish"] as const) grants.push(await grantAuthority(repository, { actor: operator, subjectType: "interactive", subjectId: identity.id, appId: "hospitality-booking", resource: "hospitality.rotations", action, scope: { kind: "organisation", ids: [] }, reason: "Isolated synthetic test" }));
  const handlers = rotationHandlers(store, async (_request, action) => authoriseRotation(repository, principal, action));
  const post = (body: unknown) => handlers.POST(new NextRequest("http://localhost/api/hospitality-rotations", { method: "POST", body: JSON.stringify(body) }));
  const get = (query: string) => handlers.GET(new NextRequest(`http://localhost/api/hospitality-rotations?${query}`));
  const draft = { action: "save-draft", requestId: "draft-one", expectedVersion: 0, configuration: rotationFixture() };
  const results = await Promise.all([post(draft), post({ ...draft, requestId: "competing-draft" })]);
  assert.deepEqual(results.map(response => response.status).sort(), [200, 409]);
  const publish = { action: "publish", requestId: "publish-one", expectedVersion: 1, draftRevision: 1, effectiveFrom: "2026-10-28", reason: "Synthetic autumn" };
  assert.equal((await post(publish)).status, 409, "missing canonical providers fail closed");
  assert.equal((await store.head()).version, 1);
  for (const n of [1, 2, 3]) await db.collection("fikaMenuPlanningCatalogue").doc(`dish:${n}`).set({ kind: "dish", record: { canonicalId: `dish:${n}`, revision: 1, reviewStatus: "unreviewed", methodSteps: ["Original recipe"], allergenEvidence: [] } });
  await db.collection("integrationHubCanonical").doc(stableDocumentId("item:rotation")).set({ canonicalId: "item:rotation", entityType: "Hospitality Menu Item", lifecycleStatus: "active", record: { lifecycleState: "active" } });
  const published = await post(publish); assert.equal(published.status, 200);
  assert.equal((await post(publish)).status, 200);
  assert.equal((await post({ ...publish, reason: "Changed reuse" })).status, 409);
  assert.equal((await store.head()).version, 2);
  const frozen = await store.revision(2);
  await db.collection("fikaMenuPlanningCatalogue").doc("dish:1").update({ "record.revision": 2, "record.methodSteps": ["Changed"] });
  assert.deepEqual(await store.revision(2), frozen);
  assert.equal((await get("date=2026-10-27")).status, 404);
  assert.equal((await get("date=2026-10-28")).status, 200);
  assert.equal((await get("mode=revision&revision=1")).status, 403);
  assert.equal((await get("mode=manage")).status, 200);
  assert.equal((await post({ ...draft, requestId: "draft-two", expectedVersion: 2 })).status, 200);
  assert.equal((await post({ ...publish, requestId: "stale-recipe", draftRevision: 3, expectedVersion: 3, effectiveFrom: "2026-12-01" })).status, 409);
  assert.equal((await store.head()).version, 3);
  const nextConfig = rotationFixture(); nextConfig.groups[0].dishBank[0].recipeRevision = 2;
  assert.equal((await post({ ...draft, requestId: "draft-three", expectedVersion: 3, configuration: nextConfig })).status, 200);
  assert.equal((await post({ ...publish, requestId: "future-season", draftRevision: 4, expectedVersion: 4, effectiveFrom: "2026-12-01" })).status, 200);
  assert.equal((await store.published("2026-11-30")).revision.revision, 2);
  assert.equal((await store.published("2026-12-01")).revision.revision, 5);
  assert.equal((await post({ ...publish, requestId: "rewrite-history", draftRevision: 4, expectedVersion: 5, effectiveFrom: "2026-10-27" })).status, 422);
  await revokeAuthority(repository, { grantId: grants.find(grant => grant.action === "Manage")!.id, actor: principal, reason: "Synthetic revoke" });
  assert.equal((await post({ ...draft, requestId: "revoked", expectedVersion: 5 })).status, 403);
  assert.equal((await get("mode=manage")).status, 403);
  assert.equal((await get("date=2026-12-01")).status, 200, "View does not acquire management");
  const access = await (await get("mode=access")).json();
  assert.deepEqual(access.permissions, { View: true, Manage: false, Publish: true });
  const root = db.collection(ROTATION_COLLECTION).doc("company");
  assert.equal((await root.collection("revisions").get()).size, 5);
  assert.equal((await root.collection("commands").get()).size, 5);
  const unauthenticated = rotationHandlers(store);
  assert.equal((await unauthenticated.GET(new NextRequest("http://localhost/api/hospitality-rotations?date=2026-12-01"))).status, 401);
  await root.collection("revisions").doc("5").update({ "configuration.label": "Tampered evidence" });
  assert.equal((await get("date=2026-12-01")).status, 503, "Corrupt immutable evidence is never served as current");
  await root.collection("revisions").doc("4").update({ "configuration.label": "Tampered draft" });
  assert.equal((await post({ ...publish, requestId: "corrupt-draft", expectedVersion: 5, draftRevision: 4, effectiveFrom: "2027-01-01" })).status, 503, "Publication also verifies immutable draft evidence");
  assert.equal((await store.head()).version, 5);
});
