import test from "node:test";
import assert from "node:assert/strict";
import { db } from "../lib/firebase-admin";
import { stableDocumentId } from "../lib/canonical-editor";
import { runCatalogueCommand } from "../lib/hospitality-catalogue-admin";
import type { Actor } from "../lib/auth";
import type { CanonicalRecord } from "../lib/types";
const enabled = process.env.FIKA_PROVIDER_MAPPING_EMULATOR_TEST === "true";
test("emulator: explicit provider links are atomic, audited, versioned and unique under concurrent claims", { skip: !enabled }, async () => {
  assert.equal(process.env.FIREBASE_PROJECT_ID, "demo-fika-os");
  assert.equal(process.env.FIKA_RUNTIME_MODE, "local");
  assert.match(process.env.FIRESTORE_EMULATOR_HOST || "", /^(127\.0\.0\.1|localhost):\d+$/);
  const canonical = db.collection("integrationHubCanonical"), audit = db.collection("integrationHubGovernanceAudit");
  assert.equal((await canonical.limit(1).get()).empty, true, "Use a fresh isolated emulator; never clear a shared store");
  const stamp = "2026-10-29T12:00:00.000Z";
  const seed = async (id: string) => {
    const record = { schemaVersion: "0.1.0", version: 1, createdAt: stamp, createdBy: "synthetic-seed", updatedAt: stamp, updatedBy: "synthetic-seed", active: true, externalIdentities: [], provenanceIds: [], ownership: { providerOwned: {}, fikaOwned: {} }, entityType: "Hospitality Menu Item", canonicalId: id, name: "Synthetic Item", category: "Synthetic", lifecycleState: "active", defaultMinimumQuantity: 8, dietaryInformation: [], allergenInformation: [], providerMappings: [{ provider: "mnk-booking-platform", sourceItemId: id }] };
    const item: CanonicalRecord = { canonicalId: id, entityType: "Hospitality Menu Item", record, dataHash: "synthetic", lifecycleStatus: "published", publicationStatus: "published", publishedAt: stamp };
    await canonical.doc(stableDocumentId(id)).set(item); return item;
  };
  const admin: Actor = { uid: "synthetic:mapping-admin", name: "Synthetic mapping administrator", role: "integration-admin", synthetic: true };
  const one = await seed("hospitality-menu-item:synthetic-one");
  const link = { action: "link-provider-item" as const, itemId: one.canonicalId, expectedVersion: 1, provider: "cfc-hospitality-brochure", sourceItemId: "deli-sandwich-lunch", sourceVersion: "synthetic-source" };
  await assert.rejects(runCatalogueCommand({ ...admin, role: "viewer" }, link), /Permission denied/);
  assert.equal((await audit.get()).size, 0);
  await runCatalogueCommand(admin, link);
  const linked = (await canonical.doc(stableDocumentId(one.canonicalId)).get()).data() as CanonicalRecord;
  assert.equal(linked.record.version, 2); assert.equal(linked.canonicalId, one.canonicalId);
  assert.equal(linked.record.defaultMinimumQuantity, 8);
  assert.deepEqual(linked.record.allergenInformation, []);
  assert.equal((linked.record.providerMappings as unknown[]).length, 2);
  const events = await audit.get(); assert.equal(events.size, 1);
  assert.equal(events.docs[0].data().actorId, admin.uid);
  assert.equal(events.docs[0].data().details.provider, link.provider);
  await assert.rejects(runCatalogueCommand(admin, link), /changed elsewhere/);
  await runCatalogueCommand(admin, { ...link, expectedVersion: 2 });
  assert.equal((await audit.get()).size, 1, "No-op and rejected commands leave no duplicate event");
  const other = await seed("hospitality-menu-item:synthetic-two");
  const third = await seed("hospitality-menu-item:synthetic-three");
  const claims = await Promise.allSettled([other, third].map(item => runCatalogueCommand(admin, { ...link, itemId: item.canonicalId, sourceItemId: "salad-boxes" })));
  assert.equal(claims.filter(result => result.status === "fulfilled").length, 1);
  assert.equal(claims.filter(result => result.status === "rejected").length, 1);
  const items = (await canonical.get()).docs.map(doc => doc.data() as CanonicalRecord);
  assert.equal(items.filter(item => (item.record.providerMappings as Array<{ sourceItemId: string }>).some(mapping => mapping.sourceItemId === "salad-boxes")).length, 1);
  assert.equal((await audit.get()).size, 2);
  assert.equal((await db.collection("fikaMenuPlanningCatalogue").limit(1).get()).empty, true, "Mapping never creates or reuses recipes");
  assert.equal((await db.collection("integrationHubHospitalityMenuProductionRouting").limit(1).get()).empty, true, "Linking does not invent production routing");
});
