import test from "node:test";
import assert from "node:assert/strict";
import { createElement } from "react";
import { act, create, type ReactTestInstance, type ReactTestRenderer } from "react-test-renderer";
import ImportReview from "../app/imports/ImportReview";
import { initialReview, prepareImport, reviewCompleteness } from "../app/imports/review-model";
import { previewPastedRecipes } from "../lib/import-preview";

(globalThis as typeof globalThis & { IS_REACT_ACT_ENVIRONMENT: boolean }).IS_REACT_ACT_ENVIRONMENT = true;
const text = "Name: First fixture\nType: Mocktail\nIngredient: 10 ml lime juice\nMethod: Stir.\nName: Second fixture\nType: Mocktail\nIngredient: mint leaves\nMethod: Shake.\nEquipment: Shaker";
const preview = previewPastedRecipes(text);
const findButton = (root: ReactTestInstance, label: string) => root.findAllByType("button").find(item => item.children.includes(label))!;
const findLabel = (root: ReactTestInstance, label: string) => root.findAllByType("label").find(item => item.children.filter(child => typeof child === "string").join("").trim() === label)!;

test("review payload binds the selected fingerprint, preserves all edited fields and requires confirmation", () => {
  const form = initialReview(preview.candidates[1]);
  assert.ok(reviewCompleteness(form).some(issue => issue.includes("quantity")));
  const session = { text, preview, forms: preview.candidates.map(initialReview), saved: [] as number[] };
  assert.match(prepareImport(session, 1, false, "fixture:key").error!, /Confirm/);
  session.forms[1] = { ...form, name: "Corrected fixture", beverageType: "Cold drink", description: "Reviewed description", ingredients: [{ name: "Mint sprig", amount: "1", unit: "each" }], method: "Build over ice.", glassware: "Tall glass", garnish: "Mint", equipmentText: "Spoon\nJigger", classification: "classic_source" };
  const pending = prepareImport(session, 1, true, "fixture:key").pending!;
  assert.deepEqual(JSON.parse(pending.body), { text, sourceHash: preview.sourceHash, candidateIndex: 1, candidateHash: preview.candidates[1].candidateHash, classification: "classic_source", reviewed: true, reviewedCandidate: { name: "Corrected fixture", beverageType: "Cold drink", description: "Reviewed description", ingredients: [{ name: "Mint sprig", amount: 1, unit: "each" }], method: "Build over ice.", glassware: "Tall glass", garnish: "Mint", equipment: ["Spoon", "Jigger"] } });
  session.forms[1].ingredients[0].amount = "1.2345";
  assert.match(prepareImport(session, 1, true, "fixture:key").error!, /three decimal/);
  session.forms[1].ingredients[0].amount = "1";
  session.forms[1].ingredients[0].unit = "";
  assert.match(prepareImport(session, 1, true, "fixture:key").error!, /unit/i);
  session.saved.push(1);
  assert.match(prepareImport(session, 1, true, "fixture:key").error!, /unsaved/);
});

test("component reviews multiple candidates and retries an uncertain submission with identical evidence", async t => {
  const originalFetch = globalThis.fetch;
  const calls: { url: string; body: string; key?: string }[] = [];
  let commits = 0;
  globalThis.fetch = async (input, init) => {
    const url = String(input);
    calls.push({ url, body: String(init?.body), key: (init?.headers as Record<string, string>)?.["idempotency-key"] });
    if (url.endsWith("/preview")) return Response.json(preview);
    commits++;
    if (commits === 1) throw new TypeError("network response lost");
    if (commits === 2) return Response.json({ error: { message: "Access unavailable" } }, { status: 403 });
    return Response.json({ record: { name: "Corrected fixture" }, sourceHash: preview.sourceHash }, { status: 201 });
  };
  t.after(() => { globalThis.fetch = originalFetch; });
  let rendered!: ReactTestRenderer;
  await act(async () => { rendered = create(createElement(ImportReview)); });
  t.after(() => { act(() => rendered.unmount()); });
  await act(async () => { findLabel(rendered.root, "Recipe source text").findByType("textarea").props.onChange({ target: { value: text } }); });
  await act(async () => { findButton(rendered.root, "Preview candidates").props.onClick(); });
  assert.equal(rendered.root.findAllByProps({ name: "candidate" }).length, 2);
  await act(async () => { findLabel(rendered.root, "Drink name").findByType("input").props.onChange({ target: { value: "First edited" } }); });
  await act(async () => { rendered.root.findAllByProps({ name: "candidate" })[1].props.onChange(); });
  await act(async () => { rendered.root.findAllByProps({ name: "candidate" })[0].props.onChange(); });
  assert.equal(findLabel(rendered.root, "Drink name").findByType("input").props.value, "First edited");
  await act(async () => { rendered.root.findAllByProps({ name: "candidate" })[1].props.onChange(); });
  const change = async (label: string, type: "input" | "textarea" | "select", value: string) => { await act(async () => { findLabel(rendered.root, label).findByType(type).props.onChange({ target: { value } }); }); };
  await change("Drink name", "input", "Corrected fixture");
  await change("Drink type", "input", "Cold drink");
  await change("Description", "textarea", "Reviewed description");
  await change("Ingredient 1", "input", "Mint sprig");
  await change("Quantity", "input", "1");
  await change("Unit", "input", "each");
  await change("Preparation method", "textarea", "Build over ice.");
  await change("Glassware", "input", "Tall glass");
  await change("Garnish", "input", "Mint");
  await change("Equipment", "textarea", "Spoon\nJigger");
  await change("Classification", "select", "classic_source");
  await act(async () => { rendered.root.findByProps({ type: "checkbox" }).props.onChange({ target: { checked: true } }); });
  await change("Garnish", "input", "Lime");
  assert.equal(rendered.root.findByProps({ type: "checkbox" }).props.checked, false);
  await act(async () => { rendered.root.findByProps({ type: "checkbox" }).props.onChange({ target: { checked: true } }); });
  await act(async () => { findButton(rendered.root, "Create local draft").props.onClick(); });
  assert.equal(findLabel(rendered.root, "Recipe source text").findByType("textarea").props.disabled, true);
  await act(async () => { findButton(rendered.root, "Retry same request").props.onClick(); });
  assert.equal(findLabel(rendered.root, "Recipe source text").findByType("textarea").props.disabled, true, "a later denial cannot resolve the earlier unknown result");
  await act(async () => { findButton(rendered.root, "Retry same request").props.onClick(); });
  assert.equal(findButton(rendered.root, "Draft created").props.disabled, true);
  const attempts = calls.filter(call => call.url.endsWith("/commit"));
  assert.equal(attempts.length, 3);
  assert.ok(attempts.every(call => call.key === attempts[0].key && call.body === attempts[0].body));
  const body = JSON.parse(attempts[0].body);
  assert.equal(body.candidateIndex, 1);
  assert.equal(body.candidateHash, preview.candidates[1].candidateHash);
  assert.deepEqual(body.reviewedCandidate.equipment, ["Spoon", "Jigger"]);
  assert.equal(body.reviewedCandidate.garnish, "Lime");
  assert.equal(body.reviewed, true);
  await act(async () => { rendered.root.findAllByProps({ name: "candidate" })[0].props.onChange(); });
  assert.equal(findLabel(rendered.root, "Drink name").findByType("input").props.value, "First edited");
  await act(async () => { findLabel(rendered.root, "Recipe source text").findByType("textarea").props.onChange({ target: { value: text + "\nChanged source" } }); });
  assert.equal(rendered.root.findAllByProps({ name: "candidate" }).length, 0, "changing source requires a fresh preview");
});
